/**
 * Разбить массив целых положительных чисел на два массива так,
 * чтобы разность сумм элементов двух получившихся массивов была минимальна.
 */
public class Task15comments { // сложность алгоритма: время O(n × sum), память O(sum) — задача о рюкзаке

    public static void main(String[] args) {
        // Исходный массив
        int[] arr = { 1, 6, 11, 5 };

        // Вызываем функцию и выводим минимальную разность
        System.out.println("Минимальная разность: " + minDiff(arr));
    }

    // Функция нахождения минимальной разности сумм при разбиении
    public static int minDiff(int[] arr) {
        // Если массив пустой или не существует — возвращаем 0
        if (arr == null || arr.length == 0) {
            return 0;
        }

        // Сумма всех элементов массива
        int total = 0;
        for (int num : arr) {
            total += num;
        }

        // Цель — найти подмножество с суммой, максимально близкой к половине total
        int target = total / 2;

        // dp[s] — можно ли из элементов массива набрать сумму s.
        // Массив размером target + 1 (суммы от 0 до target).
        boolean[] dp = new boolean[target + 1];

        // Сумму 0 можно набрать всегда — просто ничего не берём
        dp[0] = true;

        // Перебираем все элементы массива
        for (int num : arr) {
            // Идём по всем возможным суммам справа налево,
            // чтобы не использовать один элемент дважды
            for (int s = target; s >= num; s--) {
                // Если сумму (s - num) можно набрать, то сумму s тоже можно —
                // добавляем текущий элемент
                if (dp[s - num]) {
                    dp[s] = true;
                }
            }
        }

        // Находим максимальную сумму <= target, которую реально набрать
        int sum1 = 0;
        for (int s = target; s >= 0; s--) {
            if (dp[s]) {
                sum1 = s;
                break;
            }
        }

        // Второй массив получит оставшиеся элементы
        int sum2 = total - sum1;

        // Возвращаем модуль разности сумм
        return Math.abs(sum1 - sum2);
    }
}