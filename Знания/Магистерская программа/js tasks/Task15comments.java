/**
 * Разбить массив целых положительных чисел на два массива так,
 * чтобы разность сумм элементов двух получившихся массивов была минимальна.
 */
public class Task15comments { // сложность алгоритма: время O(n × sum), память O(sum) — задача о рюкзаке

    public static void main(String[] args) {
        // Исходный массив положительных чисел
        int[] arr = { 1, 6, 11, 5 };

        // вызываем функцию и выводим минимальную разность
        System.out.println(function(arr));
    }

    // функция нахождения минимальной разности сумм при разбиении
    public static int function(int[] arr) {

        // считаем сумму всех элементов массива
        int total = 0;
        for (int num : arr)
            total += num;

        // target — половина общей суммы
        int target = total / 2;

        // массив логических значений
        boolean[] dp = new boolean[target + 1];

        // сумму 0 можно набрать всегда — просто ничего не берём
        dp[0] = true;

        // перебираем все элементы массива
        for (int num : arr) {
            // идём по всем суммам СПРАВА НАЛЕВО
            for (int s = target; s >= num; s--) {
                if (dp[s - num]) // если сумму (s - num) можно набрать без текущего элемента,
                    dp[s] = true; // то сумму s можно набрать, добавив текущий элемент
            }
        }

        // находим максимальную сумму <= target
        int sum = 0;
        for (int s = target; s >= 0; s--) {
            if (dp[s]) {
                sum = s;
                break; // нашли ближайшую к target сумму — выходим
            }
        }

        // возвращаем разность сумм двух кучек (всегда положительная)
        return total - 2 * sum;
    }
}