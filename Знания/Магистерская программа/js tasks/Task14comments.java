/**
 * Найти самую длинную неубывающую последовательность в массиве целых чисел
 * (последовательность не обязательно должна быть непрерывной).
 */
public class Task14comments {

    public static void main(String[] args) {
        // Исходный массив
        int[] arr = { 3, 1, 4, 2, 5, 3, 7 };

        // Вызываем функцию и получаем самую длинную неубывающую последовательность
        int[] result = longest(arr);

        // Выводим длину
        System.out.println("Длина: " + result.length);

        // Выводим саму последовательность
        System.out.print("Последовательность: ");
        for (int num : result) {
            System.out.print(num + " ");
        }
    }

    // Функция поиска самой длинной неубывающей подпоследовательности
    public static int[] longest(int[] arr) {
        // Если массив пустой или не существует — возвращаем пустой массив
        if (arr == null || arr.length == 0) {
            return new int[0];
        }

        int n = arr.length;

        // dp[i] — длина самой длинной цепочки, заканчивающейся на arr[i]
        int[] dp = new int[n];

        // prev[i] — индекс предыдущего элемента в этой цепочке
        // -1 означает «начала нет», т.е. это начало цепочки
        int[] prev = new int[n];

        // maxIdx — индекс, где заканчивается самая длинная цепочка (пока — первый)
        int maxIdx = 0;

        // Перебираем все элементы массива
        for (int i = 0; i < n; i++) {

            // Изначально считаем, что элемент arr[i] — это цепочка длиной 1,
            // состоящая только из него самого. Предыдущего элемента нет (-1).
            dp[i] = 1;
            prev[i] = -1;

            // Смотрим ВСЕ предыдущие элементы arr[j] (j < i)
            for (int j = 0; j < i; j++) {

                // Если arr[j] <= arr[i], значит к цепочке, заканчивающейся на j,
                // МОЖНО приписать arr[i].
                // Если при этом получается длина больше, чем уже найдено для i —
                // обновляем dp[i] и запоминаем, что пришли из j.
                if (arr[j] <= arr[i] && dp[j] + 1 > dp[i]) {
                    dp[i] = dp[j] + 1; // новая, более длинная цепочка
                    prev[i] = j; // запоминаем, откуда пришли
                }
            }

            // Если цепочка, заканчивающаяся на i, длиннее текущего рекорда —
            // обновляем рекорд (запоминаем индекс i)
            if (dp[i] > dp[maxIdx]) {
                maxIdx = i;
            }
        }

        // Восстанавливаем цепочку по ссылкам prev, идя с конца
        int length = dp[maxIdx]; // длина самой длинной цепочки
        int[] result = new int[length]; // массив для результата
        int cur = maxIdx; // начинаем с последнего элемента цепочки

        // Идём от конца к началу, заполняя result
        for (int i = length - 1; i >= 0; i--) {
            result[i] = arr[cur]; // записываем текущий элемент цепочки
            cur = prev[cur]; // переходим к предыдущему элементу цепочки
        }

        // Возвращаем найденную последовательность
        return result;
    }
}