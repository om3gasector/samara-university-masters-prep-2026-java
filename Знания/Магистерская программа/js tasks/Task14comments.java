/**
 * Найти самую длинную неубывающую последовательность в массиве целых чисел
 * (последовательность не обязательно должна быть непрерывной).
 */
public class Task14comments { // сложность алгоритма: время O(n²), память O(n) — динамическое программирование

    public static void main(String[] args) {
        // Исходный массив
        int[] arr = { 3, 1, 4, 2, 5 };
        int[] result = function(arr);

        // Выводим длину
        System.out.println("Длина: " + result.length);

        // Выводим последовательность
        System.out.print("Последовательность: ");
        for (int num : result) {
            System.out.print(num + " ");
        }
    }

    // Функция поиска самой длинной неубывающей подпоследовательности
    public static int[] function(int[] arr) {
        // ессли массив пустой или не существует — возвращаем пустой массив
        if (arr == null || arr.length == 0) {
            return new int[0];
        }

        int n = arr.length; // длина массива
        int[] dp = new int[n]; // длина самой длинной цепочки
        int[] prev = new int[n]; // индекс предыдущего элемента в этой цепочке
        int maxIdx = 0; // индекс, где заканчивается самая длинная цепочка

        // Перебираем все элементы массива
        for (int i = 0; i < n; i++) {
            dp[i] = 1; // изначально считаем, что элемент arr[i] — это цепочка длиной 1,
            prev[i] = -1; // предыдущего элемента нет (-1)

            // смотрим ВСЕ предыдущие элементы arr[j] (j < i)
            for (int j = 0; j < i; j++) {

                // если этот элемент меньше или равен чем текущий И
                // еслли эта новая цепочка длиннее, чем уже найденная,
                // обновляем длину и запоминаем откуда пришли
                if (arr[j] <= arr[i] && dp[j] + 1 > dp[i]) {
                    dp[i] = dp[j] + 1; // записываем новую, более длинную цепочку
                    prev[i] = j; // запоминаем, откуда пришли
                }
            }

            // если цепочка длиннее текущего рекорда — обновляем рекорд
            if (dp[i] > dp[maxIdx]) {
                maxIdx = i;
            }
        }

        // Восстанавливаем цепочку
        int length = dp[maxIdx]; // переменная длина - длиной рекорда
        int[] result = new int[length]; // массив для результата
        int cur = maxIdx; // начинаем с последнего элемента цепочки

        // идем от конца к началу, заполняя result
        for (int i = length - 1; i >= 0; i--) {
            result[i] = arr[cur]; // записываем текущий элемент цепочки
            cur = prev[cur]; // переходим к предыдущему элементу цепочки
        }

        // Возвращаем найденную последовательность
        return result;
    }
}