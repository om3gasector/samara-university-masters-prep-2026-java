/**
 * Найти медиану в массиве вещественных чисел.
 * Медиана: массив сортируется по возрастанию.
 * Нечётное количество — центральный элемент.
 * Чётное количество — среднее арифметическое двух центральных.
 */
public class Task8comments {

    public static void main(String[] args) {
        // Исходный массив вещественных чисел
        double[] arr = { 5.2, 1.8, 9.4, 3.6, 7.1 };

        // Вызываем функцию и выводим результат
        double result = median(arr);
        System.out.println(result);
    }

    // Функция нахождения медианы
    public static double median(double[] arr) {
        // Если массив не существует или пустой — возвращаем 0
        if (arr == null || arr.length == 0) {
            return 0;
        }

        // Создаём копию массива, чтобы не менять исходный
        // clone() создаёт точную копию массива
        double[] sorted = arr.clone();

        // Пузырьковая сортировка по возрастанию
        // Внешний цикл — номер прохода (всего нужно n-1 проходов)
        for (int i = 0; i < sorted.length - 1; i++) {

            // Внутренний цикл — сравниваем соседние пары
            // sorted.length - 1 - i — не проверяем уже отсортированный конец
            for (int j = 0; j < sorted.length - 1 - i; j++) {

                // Если левый элемент больше правого — меняем их местами
                if (sorted[j] > sorted[j + 1]) {

                    // Обмен через временную переменную temp
                    double temp = sorted[j]; // запомнили левый эл. во временную переменную
                    sorted[j] = sorted[j + 1]; // на место левого записали правый
                    sorted[j + 1] = temp; // на место правого запишем сохраненный левый
                }
            }
        }

        // После сортировки массив упорядочен по возрастанию
        int n = sorted.length; // количество элементов
        int mid = n / 2; // индекс середины (для 5 элементов = 2, для 6 = 3)

        // Если количество элементов нечётное — возвращаем центральный
        // n % 2 — остаток от деления на 2. Если не 0, то нечётное
        if (n % 2 != 0) {
            return sorted[mid]; // центральный элемент
        } else {
            // Если чётное — среднее арифметическое двух центральных
            // 2.0 пишем, чтобы было вещественное деление, а не целочисленное
            return (sorted[mid - 1] + sorted[mid]) / 2.0;
        }
    }
}